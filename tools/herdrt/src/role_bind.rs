fn rx_name() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^[a-z][a-z0-9_-]{0,31}$").unwrap())
}
fn rx_run() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$").unwrap())
}
fn rx_model() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^[a-zA-Z0-9][a-zA-Z0-9._-]{0,79}$").unwrap())
}
fn rx_opencode_model() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^[a-zA-Z0-9][a-zA-Z0-9._-]{0,79}/[a-zA-Z0-9][a-zA-Z0-9._:-]{0,79}$").unwrap())
}
fn rx_task_id() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^T[0-9]{2,4}$").unwrap())
}

/// python re.fullmatch over an anchored pattern: our patterns have ^...$ anchors,
/// so is_match is the full-string check.
fn fullmatch(re: &Regex, s: &str) -> bool {
    re.is_match(s)
}

fn kind_allowed(role: &str, kind: &str) -> bool {
    match role {
        "manager" | "delegator" | "lead" => ["claude", "codex", "opencode"].contains(&kind),
        "worker" => ["agy", "codex", "claude", "opencode"].contains(&kind),
        "verifier" | "critic" => ["claude", "codex", "agy", "opencode"].contains(&kind),
        _ => false,
    }
}

fn preference(role: &str, kind: &str) -> Option<(&'static str, Option<&'static str>)> {
    // (role, kind) -> PREFERENCES key lookup from role_bind.py lines 75-80.
    match (role, kind) {
        ("worker", "codex") => Some(("gpt-6-luna", Some("xhigh"))),
        ("worker", "claude") => Some(("claude-haiku-5-5", None)),
        ("verifier", "claude") => Some(("claude-haiku-5-5", None)),
        ("worker", "opencode") => Some(("opencode/deepseek-v4.1-flash-free", None)),
        ("verifier", "opencode") => Some(("opencode/glm-5.3-flash-free", None)),
        ("critic", "claude") => Some(("claude-sonnet-5-5", None)),
        _ => None,
    }
}

// --- python value semantics helpers ------------------------------------------

/// dict.get(key) -> Option<Value> (absent -> None; present-null -> Some(Null)).
fn get<'a>(v: &'a Value, key: &str) -> Option<&'a Value> {
    v.as_object().and_then(|o| o.get(key))
}

/// Python truthiness.
fn truthy(v: &Value) -> bool {
    match v {
        Value::Null => false,
        Value::Bool(b) => *b,
        Value::Number(n) => n.as_f64().map(|f| f != 0.0).unwrap_or(true),
        Value::String(s) => !s.is_empty(),
        Value::Array(a) => !a.is_empty(),
        Value::Object(o) => !o.is_empty(),
    }
}

/// str(int/float) python formatting for JSON numbers.
fn py_number_str(n: &serde_json::Number) -> String {
    if let Some(i) = n.as_i64() {
        return i.to_string();
    }
    if let Some(u) = n.as_u64() {
        return u.to_string();
    }
    match n.as_f64() {
        Some(f) => {
            let base = format!("{:?}", f);
            // python always shows e+NN / e-NN with two exponent digits; closest cheap match
            base.replace("e0", "e+0").replace("e+e", "e+")
        }
        None => n.to_string(),
    }
}

/// Python str(v) for f-string style interpolation.
fn py_str(v: &Value) -> String {
    match v {
        Value::Null => "None".into(),
        Value::Bool(b) => if *b { "True" } else { "False" }.into(),
        Value::Number(n) => py_number_str(n),
        Value::String(s) => s.clone(),
        Value::Array(a) => format!(
            "[{}]",
            a.iter().map(py_repr).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(o) => format!(
            "{{{}}}",
            o.iter()
                .map(|(k, val)| format!("{}: {}", py_repr(&Value::String(k.clone())), py_repr(val)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// Python repr(v). Strings approximating CPython's quoting rules.
fn py_repr(v: &Value) -> String {
    match v {
        Value::Null => "None".into(),
        Value::Bool(b) => if *b { "True" } else { "False" }.into(),
        Value::Number(n) => py_number_str(n),
        Value::String(s) => py_repr_str(s),
        Value::Array(a) => format!(
            "[{}]",
            a.iter().map(py_repr).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(o) => format!(
            "{{{}}}",
            o.iter()
                .map(|(k, val)| format!("{}: {}", py_repr(&Value::String(k.clone())), py_repr(val)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn py_repr_str(s: &str) -> String {
    // shortcut: strings containing both quote kinds show triple-quote reprs in
    // CPython; those only appear in error paths for invalid user input.
    let (quote, esc_quote) = if s.contains('\'') && !s.contains('"') {
        ('"', '"')
    } else {
        ('\'', '\'')
    };
    let mut out = String::with_capacity(s.len() + 2);
    out.push(quote);
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ if c == esc_quote => {
                out.push('\\');
                out.push(c);
            }
            _ if (c as u32) < 0x20 || (c as u32) == 0x7f => {
                out.push_str(&format!("\\x{:02x}", c as u32));
            }
            _ => out.push(c),
        }
    }
    out.push(quote);
    out
}

fn py_trim(s: &str) -> &str {
    s.trim_matches(|c: char| c.is_whitespace() || ('\u{1c}'..='\u{1f}').contains(&c))
}

/// ACTIVATION.json uses python json.dumps(..., indent=2 + ensure_ascii=True).
fn py_json_pretty(v: &Value) -> String {
    ensure_ascii(&util::json_pretty(v))
}

fn ensure_ascii(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 16);
    let mut in_str = false;
    let mut escaped = false;
    for c in s.chars() {
        if in_str {
            if escaped {
                escaped = false;
                out.push(c);
                continue;
            }
            match c {
                '\\' => {
                    escaped = true;
                    out.push('\\');
                }
                '"' => {
                    in_str = false;
                    out.push('"');
                }
                c if c.is_ascii() && (c as u32) != 0x7f => out.push(c),
                c if (c as u32) < 0x80 => out.push_str(&format!("\\u{:04x}", c as u32)),
                c => push_py_unicode(&mut out, c as u32),
            }
        } else {
            if c == '"' {
                in_str = true;
            }
            out.push(c);
        }
    }
    out
}

fn push_py_unicode(out: &mut String, cp: u32) {
    if cp <= 0xFFFF {
        out.push_str(&format!("\\u{:04x}", cp));
    } else {
        let hv = ((cp - 0x10000) >> 10) + 0xD800;
        let lv = (cp & 0x3FF) + 0xDC00;
        out.push_str(&format!("\\u{:04x}\\u{:04x}", hv, lv));
    }
}

