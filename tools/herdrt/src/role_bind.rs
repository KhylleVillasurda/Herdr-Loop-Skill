#[allow(clippy::too_many_lines)]
fn conclude(
    b: &mut Binding,
    repo_str: &str,
    run_dir: &Path,
    fresh: bool,
    force: bool,
    dry_run: bool,
) -> ToolResult<()> {
    let run_dir_str = run_dir.to_string_lossy().into_owned();
    let standalone = b.execution_mode == "standalone";
    let mut files: Vec<(PathBuf, String)> = Vec::new();
    files.push((run_dir.join("ROSTER.md"), render_roster(b, repo_str, &run_dir_str)));
    let mut activation = Map::new();
    activation.insert("run_id".into(), json!(b.run_id.clone()));
    activation.insert("repo".into(), json!(repo_str));
    activation.insert("execution_mode".into(), json!(b.execution_mode.clone()));
    activation.insert("agents".into(), Value::Array(vec![]));
    if !standalone {
        activation.insert("state_backend".into(), json!(b.backend.clone()));
        activation.insert("backend_epoch".into(), json!(b.backend_epoch.unwrap_or_default()));
    }
    let mut prompts: Vec<String> = Vec::new();
    for agent in &b.agents {
        let role = agent.role;
        let recipient = signal_recipient(role, b);
        let packet = run_dir.join("role-packets").join(format!("{}.md", agent.name));
        files.push((
            packet.clone(),
            render_packet(b, role, agent, repo_str, &run_dir_str, &recipient),
        ));
        let prompt = prompt_for(b, role, agent, &run_dir_str, &recipient);
        prompts.push(prompt.clone());
        let spawn_owner_value = if standalone {
            "none".to_string()
        } else {
            spawn_owner(role, agent, b)
        };
        let entry = json!({
            "name": agent.name.clone(),
            "kind": agent.kind.clone(),
            "role": role,
            "task_id": get(&agent.raw, "task_id").cloned().unwrap_or(json!("")),
            "attempt_id": agent.attempt_id.clone().unwrap_or_default(),
            "worktree": get(&agent.raw, "worktree").cloned().unwrap_or(json!("")),
            "task_title": agent.task_title.clone().unwrap_or_default(),
            "task_outcome": agent.task_outcome.clone().unwrap_or_default(),
            "task_contract": agent.standalone_task.clone().unwrap_or_default(),
            "workspace_path": agent.workspace_path.clone().unwrap_or_default(),
            "signal_recipient": recipient,
            "signal_transport": if standalone {
                "manual-direct"
            } else if role == "lead" {
                "human-direct"
            } else {
                "herdr-agent-prompt"
            },
            "model": agent.resolved_model.clone(),
            "reasoning_effort": agent.resolved_effort.clone(),
            "spawn_owner": spawn_owner_value,
            "requires_role_ready": !standalone,
            "prompt": prompt,
            "packet": packet.to_string_lossy().into_owned(),
        });
        activation
            .get_mut("agents")
            .and_then(Value::as_array_mut)
            .unwrap()
            .push(entry);
    }
    let mut intro: Vec<String> = if standalone {
        vec![
            MANAGED.to_string(),
            format!("# Standalone Worker assignment: {}", b.run_id),
            String::new(),
            "This is one direct human assignment. It does not create a governed run, ledger, Manager/Delegator team, or handshake.".to_string(),
            "No agent is started by this file. Paste the prompt below into the already-running assigned CLI/Herdr Worker.".to_string(),
            "If a Herdr prompt is used, do not replay after timeout until the same recipient and task artifact have been reconciled.".to_string(),
            String::new(),
        ]
    } else {
        let ledger_target = if b.backend == "sqlite" { "ledger.sqlite" } else { "SESSION.md" };
        vec![
            MANAGED.to_string(),
            format!("# Herdr activation prompts: {}", b.run_id),
            String::new(),
            format!("Selected backend: {}; epoch: {}.", b.backend, b.backend_epoch.unwrap_or_default()),
            if b.backend == "sqlite" {
                "SQLite activation records observed setup only; execution requires approved plan and separate human grant. Windows E2E promotion remains gated.".to_string()
            } else {
                "Markdown live workflow is selected.".to_string()
            },
            "The installer makes skills discoverable. The roster below **assigns** roles. Neither step starts an agent.".to_string(),
            "To activate live agents: open the relevant Herdr panes, confirm their names, then paste each prompt".to_string(),
            "through Herdr's `agent prompt` command, or use `tools/activate_roles.py` inside Herdr.".to_string(),
            "Do not dispatch Workers until Delegator copies ROLE.md and TASK.md into their worktree.".to_string(),
            format!(
                "For user-facing progress, replace Txx/attempt IDs with approved slice titles and outcomes from {}. Do not invent descriptions or acceptance.",
                ledger_target
            ),
            "This is a setup-only activation. Workers: READY.md + ROLE_READY + actual model/effort to Delegator, then WAIT for TASK_START; dedicated Haiku tester uses the Verifier role and waits for VERIFY_START + lock; Critic waits for CRITIQUE_START.".to_string(),
            "Codex Delegator: NEVER launch model-overridden Codex CLI; obtain a SPAWN_READY receipt from Claude Manager or human/non-Codex operator first.".to_string(),
            "If Herdr prompt/socket/file access is denied, classify the boundary. Request native approval only through this agent's supported tool for the same in-scope action; never grant, bypass, or disable sandbox.".to_string(),
            String::new(),
        ]
    };
    for agent in &b.agents {
        let kind = &agent.kind;
        let name = &agent.name;
        let role = agent.role;
        intro.push(format!("## {name} ({kind}, {role})"));
        intro.push(String::new());
        intro.push(prompts.remove(0));
        intro.push(String::new());
    }
    files.push((run_dir.join("ACTIVATE.md"), join_lines(intro)));

    // JSON contains no marker; only overwrite it when force is explicit and prior
    // JSON has pack provenance.
    activation.insert("generated_by".into(), json!("herdr-role-pack"));
    let json_path = run_dir.join("ACTIVATION.json");
    let new_json = format!("{}\n", py_json_pretty(&Value::Object(activation)));
    if json_path.exists() {
        let old_text = util::read_text(&json_path).map_err(|e| e.to_string())?;
        let old_json: Value = serde_json::from_str(&old_text).map_err(|e| e.to_string())?;
        if old_json.get("generated_by").and_then(Value::as_str) != Some("herdr-role-pack") {
            return Err("Refusing to replace unmanaged ACTIVATION.json".into());
        }
        if old_text != new_json && !force {
            return Err("ACTIVATION.json differs; pass --force to update".into());
        }
    }
    for (path, content) in &files {
        if path.exists() && util::read_text(path).map_err(|e| e.to_string())? != content.as_str() {
            if !force || !util::read_text(path).map_err(|e| e.to_string())?.starts_with(MANAGED) {
                return Err(format!(
                    "Refusing changed/unmanaged output: {} (use --force for generated files)",
                    path.display()
                ));
            }
        }
    }

    if fresh && !dry_run {
        // Phase-1 sqlite boundary: herdr_ledger bootstrap never runs from Rust.
        if !standalone && b.backend == "sqlite" {
            return Err(SQLITE_BOOTSTRAP_MSG.into());
        }
        let stage = run_dir.parent().unwrap().join(format!(
            ".{}.bind-{}",
            run_dir.file_name().unwrap_or_default().to_string_lossy(),
            std::process::id()
        ));
        if stage.exists() {
            return Err(format!(
                "BACKEND_INTEGRITY_BLOCKED: bootstrap staging directory already exists: {}",
                stage.display()
            ));
        }
        std::fs::create_dir_all(stage.parent().unwrap()).map_err(|e| e.to_string())?;
        std::fs::create_dir(&stage).map_err(|e| e.to_string())?;
        let bootstrap: ToolResult<()> = (|| {
            for (path, content) in &files {
                let rel = path.strip_prefix(run_dir).unwrap_or(path);
                let staged = stage.join(rel);
                if let Some(parent) = staged.parent() {
                    std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
                }
                std::fs::write(&staged, content).map_err(|e| e.to_string())?;
            }
            std::fs::write(stage.join("ACTIVATION.json"), &new_json).map_err(|e| e.to_string())?;
            if standalone {
                // no SESSION.md / selector / ledger
            } else if b.backend == "markdown" {
                let profile = backend::profile_from_config(&profile_config(b), repo_str);
                std::fs::write(stage.join("SESSION.md"), backend::render_session(&profile))
                    .map_err(|e| e.to_string())?;
            } else {
                // unreachable in phase 1 (refused above)
                return Err("SQLITE bootstrap unavailable in herdrt (phase 1)".into());
            }
            if !standalone {
                let profile = backend::profile_from_config(&profile_config(b), repo_str);
                backend::init_selector(
                    &stage,
                    &b.run_id,
                    &b.backend,
                    b.backend_epoch.unwrap_or(1),
                    &profile,
                )
                .map_err(|e| e.to_string())?;
            }
            std::fs::rename(&stage, run_dir).map_err(|e| e.to_string())?;
            Ok(())
        })();
        if let Err(_e) = bootstrap {
            // python discards the cause and leaves the staging directory for inspection
            return Err(format!(
                "BOOTSTRAP_INCOMPLETE: inspect staging directory before retrying: {}",
                stage.display()
            ));
        }
        println!("WROTE {} mode={}", run_dir.display(), b.backend);
        if standalone {
            println!("NOTE: standalone output has no SESSION.md, SQLite ledger, or managed role handshake; no agent was started.");
        }
        return Ok(());
    }
    for (path, content) in &files {
        let status = generated_content(path, content, force, dry_run)?;
        println!("{} {}", status.to_uppercase(), path.display());
    }
    if !dry_run {
        let parent = json_path.parent().unwrap();
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        std::fs::write(&json_path, &new_json).map_err(|e| e.to_string())?;
    }
    println!(
        "{} {}",
        if dry_run { "WOULD WRITE" } else { "WROTE" },
        json_path.display()
    );
    if standalone {
        println!("NOTE: standalone output has no SESSION.md, SQLite ledger, or managed role handshake; no agent was started.");
    } else if b.backend == "sqlite" {
        let db_path = run_dir.join("ledger.sqlite");
        println!(
            "{} {}",
            if dry_run && fresh { "WOULD WRITE" } else { "PRESERVED" },
            db_path.display()
        );
    } else if b.backend == "markdown" {
        let session = run_dir.join("SESSION.md");
        println!(
            "{} {}",
            if dry_run && fresh { "WOULD WRITE" } else { "PRESERVED" },
            session.display()
        );
    }
    println!("NOTE: .herdr-loop files are local runtime context; exclude them from Git commits.");
    Ok(())
}

/// python mutates config["run_id"] = run_id before render_session; mirror it.
fn profile_config(b: &Binding) -> Value {
    let mut cfg = b.raw.clone();
    if let Some(obj) = cfg.as_object_mut() {
        obj.insert("run_id".into(), json!(b.run_id.clone()));
    }
    cfg
}

