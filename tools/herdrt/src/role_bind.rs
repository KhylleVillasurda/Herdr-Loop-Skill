// --- entry -----------------------------------------------------------------------

pub fn cli(argv: &[String]) -> i32 {
    match run(argv) {
        Ok(()) => 0,
        Err(msg) => {
            eprintln!("ERROR {}", msg);
            2
        }
    }
}

#[allow(unused_assignments)]
fn run(argv: &[String]) -> ToolResult<()> {
    let args = parse_args(argv)?;

    // repo = args.repo.expanduser().resolve(strict=True)
    let repo = std::fs::canonicalize(eos_expanduser(&args.repo.to_string_lossy()))
        .map_err(|e| e.to_string())?;
    if !repo.is_dir() {
        return Err("--repo must refer to an existing directory".into());
    }
    let repo_str = repo.to_string_lossy().into_owned();

    let mut b = read_and_validate(&args.config, args.run_id.as_deref())?;
    for warning in &b.warnings {
        eprintln!("WARNING {}", warning);
    }

    let run_dir = repo.join(".herdr-loop").join(&b.run_id);
    if run_dir.is_symlink() {
        return Err("Refusing symlink run directory".into());
    }
    let standalone = b.execution_mode == "standalone";
    let fresh = !run_dir.exists();
    if standalone {
        if !fresh {
            let activation_path = run_dir.join("ACTIVATION.json");
            for ledger in ["SESSION.md", "ledger.sqlite", "BACKEND.json"] {
                if run_dir.join(ledger).exists() {
                    return Err("Cannot bind standalone mode over a governed run or ledger".into());
                }
            }
            if activation_path.is_symlink() || !activation_path.is_file() {
                return Err("Existing run directory is not a standalone role-pack binding".into());
            }
            let old_text = util::read_text(&activation_path).map_err(|e| e.to_string())?;
            let old_activation: Value = serde_json::from_str(&old_text).map_err(|e| e.to_string())?;
            if old_activation.get("generated_by").and_then(Value::as_str) != Some("herdr-role-pack")
                || old_activation.get("execution_mode").and_then(Value::as_str) != Some("standalone")
            {
                return Err(
                    "Cannot switch an existing governed or unmanaged run to standalone mode".into(),
                );
            }
        }
        b.backend = "standalone".into();
        b.backend_epoch = None;
        for agent in &mut b.agents {
            let assigned = get(&agent.raw, "worktree").cloned().unwrap_or(Value::Null);
            let workspace = if truthy(&assigned) {
                let ws = eos_expanduser(assigned.as_str().unwrap_or(""));
                std::fs::canonicalize(&ws).map_err(|e| e.to_string())?
            } else {
                repo.clone()
            };
            if !workspace.is_dir() {
                return Err("Standalone Worker workspace must be an existing directory".into());
            }
            agent.workspace_path = Some(workspace.to_string_lossy().into_owned());
        }
        conclude(&mut b, &repo_str, &run_dir, fresh, args.force, args.dry_run)
    } else {
        let (active_backend, selector) = backend::get_active_backend(&run_dir, false)?;
        if !fresh && active_backend.is_none() {
            return Err(
                "BACKEND_INTEGRITY_BLOCKED: existing run directory has no canonical ledger".into(),
            );
        }
        // RAII: the lock is released on every early return / error path (Drop), like
        // python's finally: held_lock.__exit__().
        let mut held_lock: Option<backend::RunLock> = None;
        let (active_backend, selector): (Option<String>, Option<Value>) = if !fresh && !args.dry_run {
            let lock = backend::RunLock::acquire(&run_dir)?;
            let pair = backend::get_active_backend(&run_dir, false)?;
            held_lock = Some(lock);
            pair
        } else {
            (active_backend, selector)
        };
        // عمداً: kept for RAII — dropped at scope end releases the lock (python finally).
        let _ = &held_lock;
        let requested_backend = b.requested_backend.clone();
        if !b.state_backend_key {
            eprintln!(
                "NOTICE state_backend not set; binding markdown. Ask the human Markdown or SQLite before binding (engineering-loop \u{a7}4)."
            );
        }
        if let Some(active) = &active_backend {
            if active == "sqlite" && selector.is_none() {
                return Err(
                    "SQLITE_PILOT_NOT_LIVE: existing SQLite pilot requires explicit audit; role binding refused"
                        .to_string(),
                );
            }
            if let Some(req) = &requested_backend {
                if req != active {
                    return Err(format!(
                        "BACKEND_SWITCH_REQUIRED: Run '{}' is currently bound to '{}'. To switch to '{}', run: \
py -3 skills/herdr-engineering-loop/scripts/run_backend.py --run-dir {} switch --to {}",
                        b.run_id, active, req, run_dir.display(), req
                    ));
                }
            }
            b.backend = active.clone();
        } else {
            b.backend = requested_backend.unwrap_or_else(|| "markdown".to_string());
        }
        b.backend_epoch = Some(
            selector
                .as_ref()
                .and_then(|s| s.get("epoch"))
                .and_then(Value::as_i64)
                .unwrap_or(1),
        );
        let result = conclude(&mut b, &repo_str, &run_dir, fresh, args.force, args.dry_run);
        result
    }
}

