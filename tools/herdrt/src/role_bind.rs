struct CliArgs {
    config: PathBuf,
    repo: PathBuf,
    run_id: Option<String>,
    force: bool,
    dry_run: bool,
}

fn parse_args(argv: &[String]) -> Result<CliArgs, String> {
    let mut config: Option<String> = None;
    let mut repo: Option<String> = None;
    let mut run_id: Option<String> = None;
    let mut force = false;
    let mut dry_run = false;
    let mut i = 0;
    while i < argv.len() {
        let a = argv[i].clone();
        let (name, inline): (String, Option<String>) = if a == "--config" || a == "--repo" || a == "--run-id" {
            (a.clone(), None)
        } else if let Some(rest) = a.strip_prefix("--config=") {
            ("--config".into(), Some(rest.into()))
        } else if let Some(rest) = a.strip_prefix("--repo=") {
            ("--repo".into(), Some(rest.into()))
        } else if let Some(rest) = a.strip_prefix("--run-id=") {
            ("--run-id".into(), Some(rest.into()))
        } else if a == "--force" {
            force = true;
            i += 1;
            continue;
        } else if a == "--dry-run" {
            dry_run = true;
            i += 1;
            continue;
        } else if a == "-h" || a == "--help" {
            println!("usage: herdrt role-bind --config CONFIG --repo REPO [--run-id RUN_ID] [--force] [--dry-run]");
            std::process::exit(0);
        } else {
            return Err(format!("unrecognized arguments: {}", a));
        };
        let value = match inline {
            Some(v) => v,
            None => {
                i += 1;
                match argv.get(i) {
                    Some(v) => v.clone(),
                    None => return Err(format!("argument {}: expected one argument", name)),
                }
            }
        };
        match name.as_str() {
            "--config" => config = Some(value),
            "--repo" => repo = Some(value),
            "--run-id" => run_id = Some(value),
            _ => unreachable!(),
        }
        i += 1;
    }
    let mut missing: Vec<&str> = Vec::new();
    if config.is_none() {
        missing.push("--config");
    }
    if repo.is_none() {
        missing.push("--repo");
    }
    if !missing.is_empty() {
        return Err(format!("the following arguments are required: {}", missing.join(", ")));
    }
    Ok(CliArgs {
        config: PathBuf::from(config.unwrap()),
        repo: PathBuf::from(repo.unwrap()),
        run_id,
        force,
        dry_run,
    })
}

fn eos_home() -> String {
    std::env::var("HOME").unwrap_or_default()
}

/// python Path.expanduser (approximation: ~ and ~/prefix; ~user unsupported).
fn eos_expanduser(s: &str) -> PathBuf {
    if s == "~" {
        PathBuf::from(eos_home())
    } else if let Some(rest) = s.strip_prefix("~/") {
        PathBuf::from(eos_home()).join(rest)
    } else {
        PathBuf::from(s)
    }
}

fn with_new_suffix(path: &Path) -> PathBuf {
    // python path.with_suffix(path.suffix + ".new")
    let name = path.file_name().unwrap_or_default().to_string_lossy().into_owned();
    match path.extension() {
        Some(ext) => {
            let stem = name.strip_suffix(&format!(".{}", ext.to_string_lossy())).unwrap_or(&name);
            path.with_file_name(format!("{}.{}.new", stem, ext.to_string_lossy()))
        }
        None => path.with_file_name(format!("{}.new", name)),
    }
}

/// generated_content() from role_bind.py.
fn generated_content(path: &Path, new_contents: &str, force: bool, dry_run: bool) -> ToolResult<String> {
    if path.exists() {
        if path.is_symlink() {
            return Err(format!("Refusing to overwrite symlink: {}", path.display()));
        }
        let old = util::read_text(path).map_err(|e| e.to_string())?;
        if old == new_contents {
            return Ok("unchanged".into());
        }
        if !force {
            return Err(format!(
                "Existing generated file differs; use --force after reviewing: {}",
                path.display()
            ));
        }
        if !old.starts_with(MANAGED) {
            return Err(format!("Refusing to replace unmanaged file: {}", path.display()));
        }
    }
    if dry_run {
        return Ok("would write".into());
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let tmp = with_new_suffix(path);
    if tmp.exists() {
        return Err(format!("Refusing to overwrite staging file: {}", tmp.display()));
    }
    std::fs::write(&tmp, new_contents).map_err(|e| e.to_string())?;
    std::fs::rename(&tmp, path).map_err(|e| e.to_string())?;
    Ok("wrote".into())
}

