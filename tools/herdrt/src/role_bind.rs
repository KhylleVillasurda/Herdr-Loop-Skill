    #[test]
    fn spawn_owner_matrix() {
        // claude delegator + claude manager -> delegator
        let b = binding(vec![
            mk_agent("manager", "mgr", "claude", None),
            mk_agent("delegator", "dlg", "claude", None),
            mk_agent("worker", "wrk", "codex", None),
        ], "governed", false);
        let wrk = b.agents.last().unwrap();
        assert_eq!(spawn_owner("worker", wrk, &b), "delegator");
        // codex delegator + claude manager -> manager
        let b = binding(vec![
            mk_agent("manager", "mgr", "claude", None),
            mk_agent("delegator", "dlg", "codex", None),
            mk_agent("worker", "wrk", "codex", None),
        ], "governed", false);
        let wrk = b.agents.last().unwrap();
        assert_eq!(spawn_owner("worker", wrk, &b), "manager");
        // codex delegator + codex manager -> human
        let b = binding(vec![
            mk_agent("manager", "mgr", "codex", None),
            mk_agent("delegator", "dlg", "codex", None),
            mk_agent("worker", "wrk", "codex", None),
        ], "governed", false);
        let wrk = b.agents.last().unwrap();
        assert_eq!(spawn_owner("worker", wrk, &b), "human");
        // lead mode: claude lead -> lead, codex lead -> human
        let b = binding(vec![
            mk_agent("lead", "lead", "claude", None),
            mk_agent("worker", "wrk", "codex", None),
        ], "governed", true);
        let wrk = b.agents.last().unwrap();
        assert_eq!(spawn_owner("worker", wrk, &b), "lead");
        let b = binding(vec![
            mk_agent("lead", "lead", "codex", None),
            mk_agent("worker", "wrk", "codex", None),
        ], "governed", true);
        let wrk = b.agents.last().unwrap();
        assert_eq!(spawn_owner("worker", wrk, &b), "human");
    }

    #[test]
    fn signal_recipient_matrix() {
        let b = binding(vec![
            mk_agent("manager", "mgr", "claude", None),
            mk_agent("delegator", "dlg", "codex", None),
            mk_agent("worker", "wrk", "claude", None),
        ], "governed", false);
        assert_eq!(signal_recipient("manager", &b), "dlg");
        assert_eq!(signal_recipient("delegator", &b), "mgr");
        assert_eq!(signal_recipient("worker", &b), "dlg");
        // lead mode: everyone routes to the lead
        let b = binding(vec![
            mk_agent("lead", "lead", "claude", None),
            mk_agent("worker", "wrk", "claude", None),
        ], "governed", true);
        assert_eq!(signal_recipient("lead", &b), "the human (not a Herdr agent)");
        assert_eq!(signal_recipient("worker", &b), "lead");
        // standalone
        let b = binding(vec![mk_agent("worker", "wrk", "codex", None)],
                        "standalone", false);
        assert_eq!(signal_recipient("worker", &b), "human (direct standalone assignment)");
    }

    #[test]
    fn resolve_preference_table() {
        let mut warnings = Vec::new();
        // codex worker default: gpt-6-luna/xhigh
        let (m, e) = resolve_preference("worker", &mk_agent("worker", "wrk", "codex", None),
                                        &mut warnings, false).unwrap();
        assert_eq!(m.as_str(), Some("gpt-6-luna"));
        assert_eq!(e, "xhigh");
        // claude worker default without effort
        let (m, e) = resolve_preference("worker", &mk_agent("worker", "wrk", "claude", None),
                                        &mut warnings, false).unwrap();
        assert_eq!(m.as_str(), Some("claude-haiku-5-5"));
        assert_eq!(e, "");
        // opencode verifier default + no-model warning
        let (m, _) = resolve_preference("verifier", &mk_agent("verifier", "vv", "opencode", None),
                                        &mut warnings, false).unwrap();
        assert_eq!(m.as_str(), Some("opencode/glm-5.3-flash-free"));
        assert!(warnings.iter().any(|w| w
            == "vv: OpenCode model not set; OpenCode will use its own configured default"));
        // explicit model respected
        let (m, e) = resolve_preference("worker", &mk_agent("worker", "wrk", "codex", None),
                                        &mut warnings, false).unwrap();
        let mut a = mk_agent("worker", "wrk", "codex", Some("gpt-6-luna"));
        a.raw["reasoning_effort"] = json!("max");
        let (m2, e2) = resolve_preference("worker", &a, &mut warnings, false).unwrap();
        assert_eq!(m.as_str(), m2.as_str());
        assert_eq!(e2, "max");
        let _ = e;
        // standalone with overrides refused
        let a = mk_agent("worker", "wrk", "codex", Some("gpt-6-luna"));
        assert!(resolve_preference("worker", &a, &mut warnings, true).is_err());
        // codex worker bad effort
        let mut a = mk_agent("worker", "wrk", "codex", None);
        a.raw["reasoning_effort"] = json!("low");
        assert!(resolve_preference("worker", &a, &mut warnings, false).is_err());
        // effort on non-codex worker
        let mut a = mk_agent("worker", "wrk", "claude", None);
        a.raw["reasoning_effort"] = json!("xhigh");
        assert!(resolve_preference("worker", &a, &mut warnings, false).is_err());
        // bad claude critic model warns
        warnings.clear();
        let (m, _) = resolve_preference("critic", &mk_agent("critic", "cc", "claude", Some("claude-haiku-5-5")),
                                        &mut warnings, false).unwrap();
        assert_eq!(m.as_str(), Some("claude-haiku-5-5"));
        assert!(warnings.iter().any(|w| w.contains(
            "Critic cc uses claude-haiku-5-5; claude-sonnet-5-5 is the recommended Claude critic model")));
    }

